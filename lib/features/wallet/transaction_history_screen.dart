import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import '../../core/services/providers.dart';
import '../../core/theme/app_theme.dart';
import '../../core/utils/formatters.dart';
import '../../core/widgets/common_widgets.dart';

class TransactionHistoryScreen extends ConsumerWidget {
  const TransactionHistoryScreen({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final ledgerAsync = ref.watch(userLedgerProvider);

    return SingleChildScrollView(
      padding: const EdgeInsets.all(20),
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          const SectionHeader(
            title: 'Transaction History (Ledger)',
            subtitle:
                'Immutable double-entry financial ledger entries generated by trusted backend functions.',
          ),
          const SizedBox(height: 16),
          ledgerAsync.when(
            loading: () => const Center(child: CircularProgressIndicator()),
            error: (e, _) => ErrorStateView(message: e.toString()),
            data: (entries) {
              if (entries.isEmpty) {
                return const EmptyStateView(
                  icon: Icons.receipt_outlined,
                  title: 'No Transactions Yet',
                  message:
                      'Pack purchases, capital returns, profit payouts, buybacks, and withdrawals will appear here.',
                );
              }
              return Card(
                child: ListView.separated(
                  shrinkWrap: true,
                  physics: const NeverScrollableScrollPhysics(),
                  itemCount: entries.length,
                  separatorBuilder: (_, __) => const Divider(height: 1),
                  itemBuilder: (_, i) {
                    final e = entries[i];
                    final isCredit = e.entryType == 'credit';
                    return ListTile(
                      leading: CircleAvatar(
                        backgroundColor: isCredit
                            ? AppColors.emeraldSoft
                            : AppColors.dangerSoft,
                        child: Icon(
                          isCredit ? Icons.add : Icons.remove,
                          color: isCredit
                              ? AppColors.emeraldDark
                              : AppColors.dangerRed,
                        ),
                      ),
                      title: Text(e.description),
                      subtitle: Text(
                        '${e.accountType} • ${e.category} • ${AppFormatters.dateTime(e.createdAt)}',
                      ),
                      trailing: Column(
                        mainAxisAlignment: MainAxisAlignment.center,
                        crossAxisAlignment: CrossAxisAlignment.end,
                        children: [
                          Text(
                            '${isCredit ? '+' : '-'}${AppFormatters.pkr(e.amount)}',
                            style: TextStyle(
                              fontWeight: FontWeight.w700,
                              color: isCredit
                                  ? AppColors.emeraldDark
                                  : AppColors.dangerRed,
                            ),
                          ),
                          Text(
                            'Bal: ${AppFormatters.pkr(e.balanceAfter)}',
                            style: const TextStyle(
                                fontSize: 11, color: AppColors.textMuted),
                          ),
                        ],
                      ),
                    );
                  },
                ),
              );
            },
          ),
        ],
      ),
    );
  }
}
